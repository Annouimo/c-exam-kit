"""Package source logic and content into a single standalone Python file."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent

def build():
    catalog = json.loads((ROOT / "catalog.json").read_text(encoding="utf-8"))
    templates = {}
    for entry in catalog["modules"].values():
        for name in [entry["template"]] + entry.get("extra_templates", []):
            templates[name] = (ROOT / "templates" / name).read_text(encoding="utf-8")
    bundle = {"catalog": catalog, "templates": templates}
    notice = (ROOT.parent / "LICENSE").read_text(encoding="utf-8")
    template_notice = (ROOT.parent / "LICENSES/MIT-0.txt").read_text(encoding="utf-8")
    return ("#!/usr/bin/env python3\n# Generated by toolbox/build.py; edit source inputs.\n" +
            "".join("# " + line + "\n" for line in (notice + "\nTemplates:\n" + template_notice).splitlines()) +
            "BUNDLE = " + repr(bundle) + "\n\n" +
            (ROOT / "src/generator.py").read_text(encoding="utf-8"))

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    version = json.loads((ROOT / "catalog.json").read_text(encoding="utf-8"))["version"]
    target = ROOT / ("dist/c_toolbox_v" + version + ".py")
    content = build()
    if args.check:
        if not target.exists() or target.read_text(encoding="utf-8") != content:
            raise SystemExit("standalone generator is stale; run python toolbox/build.py")
    else:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8")
        print(target)

if __name__ == "__main__":
    main()

