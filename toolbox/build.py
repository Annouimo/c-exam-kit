"""Package source logic and content into a single standalone Python file."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent

def build():
    catalog = json.loads((ROOT / "catalog.json").read_text(encoding="utf-8"))
    templates = {}
    for entry in catalog["modules"].values():
        numeric = [path for recipe in entry.get("numeric_templates", {}).values() for path in recipe]
        for name in [entry["template"]] + entry.get("extra_templates", []) + numeric:
            templates[name] = (ROOT / "templates" / name).read_text(encoding="utf-8")
    notice = (ROOT.parent / "LICENSE").read_text(encoding="utf-8")
    template_notice = (ROOT.parent / "LICENSES/MIT-0.txt").read_text(encoding="utf-8")
    comments = "# -*- coding: utf-8 -*-\n" + "".join("# " + line + "\n" for line in notice.splitlines())
    version = catalog["version"]
    bundle = {"catalog": catalog, "templates": templates,
              "prepare": comments + (ROOT / "src/prepare.py").read_text(encoding="utf-8").replace("@VERSION@", version),
              "starter": (ROOT / "templates/starter.c").read_text(encoding="utf-8"),
              "manual": (ROOT / "docs/quick_reference.md").read_text(encoding="utf-8").replace("@VERSION@", version)}
    return ("#!/usr/bin/env python3\n# -*- coding: utf-8 -*-\n# Generated by toolbox/build.py; edit source inputs.\n" +
            "".join("# " + line + "\n" for line in (notice + "\nTemplates:\n" + template_notice).splitlines()) +
            "BUNDLE = " + ascii(bundle) + "\n\n" +
            (ROOT / "src/generator.py").read_text(encoding="utf-8") + "\n\n" +
            (ROOT / "src/installer.py").read_text(encoding="utf-8"))

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    version = json.loads((ROOT / "catalog.json").read_text(encoding="utf-8"))["version"]
    target = ROOT / ("dist/c_toolbox_v" + version + ".py")
    content = build()
    namespace = {"__name__": "toolbox_build", "__file__": str(target)}
    exec(compile(content, str(target), "exec"), namespace)
    header = namespace["all_header"]()
    outputs = {target: content,
               ROOT / ("dist/c_toolbox_all_v" + version + ".h"): header,
               ROOT / "dist/c_toolbox.h": header}
    if args.check:
        for path, expected in outputs.items():
            if not path.exists() or path.read_text(encoding="utf-8") != expected:
                raise SystemExit("stale output: " + str(path) + "; run python toolbox/build.py")
    else:
        target.parent.mkdir(parents=True, exist_ok=True)
        for path, expected in outputs.items():
            path.write_text(expected, encoding="utf-8")
        print(target)

if __name__ == "__main__":
    main()

